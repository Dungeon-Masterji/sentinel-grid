"""Generate UAE-specific Synthea Generic Module Framework (GMF v1) modules.

    python configs/synthea/build_uae_modules.py

Writes configs/synthea/resources/modules/{uae_metabolic_risk,uae_heat_illness}.json.
The wrapper copies them into synthea/src/main/resources/modules/ before each run.

Synthetic data generated by Synthea — not real patient records.

Targets (adult, alive, active condition) and how each is reached
----------------------------------------------------------------
Synthea's stock modules already produce some baseline prevalence for these. This
module *tops up* adults who don't already have the condition, so the TOPUP_*
probabilities below were calibrated empirically (see README in this folder) to
hit the targets on a seeded 10k UAE population — they are not the targets.

  condition                 target  mechanism
  T2DM 44054006             ~17%    SetAttribute diabetes=true -> stock metabolic_syndrome_care
                                    records HbA1c at wellness visits and diagnoses from it.
  Prediabetes 714628002     ~20%    SetAttribute prediabetes=true -> same care pathway.
  Hypertension 59621000     ~24%    SetAttribute hypertension=true (raises BP vitals via
                                    LifecycleModule) + ConditionOnset at a wellness visit,
                                    because stock hypertension.json only diagnoses its own
                                    onset path.
  Obesity 162864005         ~28%    ConditionOnset at a wellness visit (Synthea's BMI comes
                                    from growth charts and can't be pushed via attributes).
  Vitamin D def. 34713006   ~90%    ConditionOnset at a wellness visit.
  consanguinity_carrier     trait   SetAttribute boolean at birth; no disorder modelled.

SNOMED CT codes verified active on the International Edition via tx.fhir.org
$lookup (2026-11-12): 44054006, 714628002, 59621000, 162864005, 34713006,
34095006, 89627008, 240131006, 237840007.
"""
from __future__ import annotations

import json
from pathlib import Path

OUT = Path(__file__).resolve().parent / "resources" / "modules"

SNOMED = "SNOMED-CT"
HTN = {"system": SNOMED, "code": "59621000", "display": "Essential hypertension (disorder)"}
OBESITY = {"system": SNOMED, "code": "162864005", "display": "Body mass index 30+ - obesity (finding)"}
VITD = {"system": SNOMED, "code": "34713006", "display": "Vitamin D deficiency (disorder)"}
DEHYDRATION = {"system": SNOMED, "code": "34095006", "display": "Dehydration (disorder)"}
HYPONATREMIA = {"system": SNOMED, "code": "89627008", "display": "Hyponatremia (disorder)"}
RHABDO = {"system": SNOMED, "code": "240131006", "display": "Rhabdomyolysis (disorder)"}
ELECTROLYTE = {"system": SNOMED, "code": "237840007", "display": "Disorder of electrolytes (disorder)"}
ED_VISIT = {"system": SNOMED, "code": "50849002", "display": "Emergency room admission (procedure)"}

# Consanguinity: ~40-50% of Emirati marriages are consanguineous; Emiratis ~12%
# of residents plus some Other-Arab families -> ~8% of the simulated population
# carries the trait flag. No specific disorder is modelled.
P_CONSANGUINITY_CARRIER = 0.08

# Top-up probabilities per age stage (applied only to adults not already flagged).
# Calibrated — see module docstring.
STAGES = [("Stage0", 18), ("Stage1", 30), ("Stage2", 45)]
TOPUP = {
    #              >=18   >=30   >=45
    "diabetes":    (0.04, 0.18, 0.30),
    # Stock Synthea already exceeds the UAE targets for these two in adults
    # (US-calibrated BMI/glucose models), and a top-up module can only add, so 0.
    "prediabetes": (0.00, 0.00, 0.00),
    "hypertension": (0.02, 0.10, 0.16),
    "obesity":     (0.00, 0.00, 0.00),
}
P_VITD = 0.90


def attr(name, op="==", value=True):
    c = {"condition_type": "Attribute", "attribute": name, "operator": op}
    if op not in ("is nil", "is not nil"):
        c["value"] = value
    return c


def active(code):
    return {"condition_type": "Active Condition", "codes": [code]}


def NOT(c):
    return {"condition_type": "Not", "condition": c}


def AND(*cs):
    return {"condition_type": "And", "conditions": list(cs)}


def chance(p, yes, no):
    return {"type": "Simple", "distributed_transition": [
        {"distribution": p, "transition": yes},
        {"distribution": round(1 - p, 6), "transition": no}]}


def metabolic_module() -> dict:
    s: dict[str, dict] = {}
    s["Initial"] = {"type": "Initial", "direct_transition": "Consanguinity_Draw"}
    s["Consanguinity_Draw"] = chance(P_CONSANGUINITY_CARRIER, "Set_Carrier_True", "Set_Carrier_False")
    s["Set_Carrier_True"] = {"type": "SetAttribute", "attribute": "consanguinity_carrier",
                             "value": True, "direct_transition": "Adult_Guard"}
    s["Set_Carrier_False"] = {"type": "SetAttribute", "attribute": "consanguinity_carrier",
                              "value": False, "direct_transition": "Adult_Guard"}
    s["Adult_Guard"] = {"type": "Guard", "allow": {"condition_type": "Age", "operator": ">=",
                                                   "quantity": 18, "unit": "years"},
                        "direct_transition": "VitD_Draw"}
    s["VitD_Draw"] = chance(P_VITD, "Set_VitD_Pending", "Stage0_Guard")
    s["Set_VitD_Pending"] = {"type": "SetAttribute", "attribute": "uae_vitd_pending",
                             "value": True, "direct_transition": "Stage0_Guard"}

    stages = [(name, age, i) for i, (name, age) in enumerate(STAGES)]
    for idx, (stage, age, col) in enumerate(stages):
        nxt_stage = stages[idx + 1][0] + "_Guard" if idx + 1 < len(stages) else "Terminal"
        s[f"{stage}_Guard"] = {"type": "Guard", "allow": {"condition_type": "Age", "operator": ">=",
                                                          "quantity": age, "unit": "years"},
                               "direct_transition": f"{stage}_Diabetes_Check"}
        # diabetes: skip if already diabetic
        s[f"{stage}_Diabetes_Check"] = {"type": "Simple", "conditional_transition": [
            {"condition": attr("diabetes"), "transition": f"{stage}_Prediabetes_Check"},
            {"transition": f"{stage}_Diabetes_Draw"}]}
        s[f"{stage}_Diabetes_Draw"] = chance(TOPUP["diabetes"][col], f"{stage}_Set_Diabetes",
                                             f"{stage}_Prediabetes_Check")
        s[f"{stage}_Set_Diabetes"] = {"type": "SetAttribute", "attribute": "diabetes", "value": True,
                                      "direct_transition": f"{stage}_Prediabetes_Check"}
        # prediabetes: skip if diabetic or already prediabetic
        s[f"{stage}_Prediabetes_Check"] = {"type": "Simple", "conditional_transition": [
            {"condition": {"condition_type": "Or", "conditions": [attr("diabetes"), attr("prediabetes")]},
             "transition": f"{stage}_Hypertension_Check"},
            {"transition": f"{stage}_Prediabetes_Draw"}]}
        s[f"{stage}_Prediabetes_Draw"] = chance(TOPUP["prediabetes"][col], f"{stage}_Set_Prediabetes",
                                                f"{stage}_Hypertension_Check")
        s[f"{stage}_Set_Prediabetes"] = {"type": "SetAttribute", "attribute": "prediabetes",
                                         "value": True, "direct_transition": f"{stage}_Hypertension_Check"}
        # hypertension
        s[f"{stage}_Hypertension_Check"] = {"type": "Simple", "conditional_transition": [
            {"condition": attr("hypertension"), "transition": f"{stage}_Obesity_Check"},
            {"transition": f"{stage}_Hypertension_Draw"}]}
        s[f"{stage}_Hypertension_Draw"] = chance(TOPUP["hypertension"][col], f"{stage}_Set_Hypertension",
                                                 f"{stage}_Obesity_Check")
        s[f"{stage}_Set_Hypertension"] = {"type": "SetAttribute", "attribute": "hypertension",
                                          "value": True, "direct_transition": f"{stage}_Set_HTN_Pending"}
        s[f"{stage}_Set_HTN_Pending"] = {"type": "SetAttribute", "attribute": "uae_htn_pending",
                                         "value": True, "direct_transition": f"{stage}_Obesity_Check"}
        # obesity
        s[f"{stage}_Obesity_Check"] = {"type": "Simple", "conditional_transition": [
            {"condition": attr("uae_obesity_pending"), "transition": f"{stage}_Wellness"},
            {"transition": f"{stage}_Obesity_Draw"}]}
        s[f"{stage}_Obesity_Draw"] = chance(TOPUP["obesity"][col], f"{stage}_Set_Obesity_Pending",
                                            f"{stage}_Wellness")
        s[f"{stage}_Set_Obesity_Pending"] = {"type": "SetAttribute", "attribute": "uae_obesity_pending",
                                             "value": True, "direct_transition": f"{stage}_Wellness"}
        # Diagnose module-owned conditions at the next wellness visit.
        s[f"{stage}_Wellness"] = {"type": "Encounter", "wellness": True,
                                  "direct_transition": f"{stage}_Dx_HTN_Check"}
        s[f"{stage}_Dx_HTN_Check"] = {"type": "Simple", "conditional_transition": [
            {"condition": AND(attr("uae_htn_pending"), NOT(active(HTN))), "transition": f"{stage}_Dx_HTN"},
            {"transition": f"{stage}_Dx_Obesity_Check"}]}
        s[f"{stage}_Dx_HTN"] = {"type": "ConditionOnset", "codes": [HTN],
                                "direct_transition": f"{stage}_Dx_Obesity_Check"}
        s[f"{stage}_Dx_Obesity_Check"] = {"type": "Simple", "conditional_transition": [
            {"condition": AND(attr("uae_obesity_pending"), NOT(active(OBESITY))),
             "transition": f"{stage}_Dx_Obesity"},
            {"transition": f"{stage}_Dx_VitD_Check"}]}
        s[f"{stage}_Dx_Obesity"] = {"type": "ConditionOnset", "codes": [OBESITY],
                                    "direct_transition": f"{stage}_Dx_VitD_Check"}
        s[f"{stage}_Dx_VitD_Check"] = {"type": "Simple", "conditional_transition": [
            {"condition": AND(attr("uae_vitd_pending"), NOT(active(VITD))), "transition": f"{stage}_Dx_VitD"},
            {"transition": nxt_stage}]}
        s[f"{stage}_Dx_VitD"] = {"type": "ConditionOnset", "codes": [VITD], "direct_transition": nxt_stage}

    s["Terminal"] = {"type": "Terminal"}
    return {
        "name": "UAE Metabolic Risk",
        "remarks": [
            "Sentinel Grid: raises adult prevalence of T2DM, prediabetes, hypertension, obesity",
            "and vitamin D deficiency to UAE-plausible levels, and sets a consanguinity_carrier trait.",
            "Generated by configs/synthea/build_uae_modules.py — edit that, not this file.",
            "Synthetic data generated by Synthea — not real patient records."],
        "gmf_version": 1,
        "states": s,
    }


# Heat illness: monthly hazard per adult, by month (1-12). Low-SES adults (proxy for
# outdoor manual labour) get HEAT_LOW_SES_MULTIPLIER x. Peak Jun-Sep.
HEAT_MONTHLY = {1: 0.0002, 2: 0.0002, 3: 0.0005, 4: 0.0012, 5: 0.0025, 6: 0.0050,
                7: 0.0070, 8: 0.0070, 9: 0.0045, 10: 0.0020, 11: 0.0006, 12: 0.0002}
HEAT_LOW_SES_MULTIPLIER = 3.0


def heat_module() -> dict:
    s: dict[str, dict] = {}
    s["Initial"] = {"type": "Initial", "direct_transition": "Adult_Guard"}
    s["Adult_Guard"] = {"type": "Guard", "allow": {"condition_type": "Age", "operator": ">=",
                                                   "quantity": 18, "unit": "years"},
                        "direct_transition": "Monthly_Delay"}
    s["Monthly_Delay"] = {"type": "Delay", "exact": {"quantity": 1, "unit": "months"},
                          "direct_transition": "Route_By_Month"}
    s["Route_By_Month"] = {"type": "Simple", "conditional_transition": [
        {"condition": {"condition_type": "Age", "operator": ">", "quantity": 70, "unit": "years"},
         "transition": "Terminal"}] + [
        {"condition": {"condition_type": "Date", "operator": "==", "month": m},
         "transition": f"Month_{m:02d}_SES"} for m in range(1, 13)]}
    for m, p in HEAT_MONTHLY.items():
        hi = min(p * HEAT_LOW_SES_MULTIPLIER, 0.5)
        s[f"Month_{m:02d}_SES"] = {"type": "Simple", "conditional_transition": [
            {"condition": {"condition_type": "Socioeconomic Status", "category": "Low"},
             "transition": f"Month_{m:02d}_Low"},
            {"transition": f"Month_{m:02d}_Other"}]}
        s[f"Month_{m:02d}_Low"] = chance(round(hi, 6), "Heat_Illness_Type", "Monthly_Delay")
        s[f"Month_{m:02d}_Other"] = chance(p, "Heat_Illness_Type", "Monthly_Delay")
    # Primary diagnosis mix for a heat-related ED presentation.
    s["Heat_Illness_Type"] = {"type": "Simple", "distributed_transition": [
        {"distribution": 0.70, "transition": "Onset_Dehydration"},
        {"distribution": 0.15, "transition": "Onset_Hyponatremia"},
        {"distribution": 0.10, "transition": "Onset_Electrolyte"},
        {"distribution": 0.05, "transition": "Onset_Rhabdo"}]}
    for name, code in [("Dehydration", DEHYDRATION), ("Hyponatremia", HYPONATREMIA),
                       ("Electrolyte", ELECTROLYTE), ("Rhabdo", RHABDO)]:
        s[f"Onset_{name}"] = {"type": "ConditionOnset", "codes": [code], "target_encounter": "Heat_ED_Visit",
                              "assign_to_attribute": "uae_heat_condition",
                              "direct_transition": "Heat_ED_Visit"}
    s["Heat_ED_Visit"] = {"type": "Encounter", "encounter_class": "emergency",
                          "reason": "uae_heat_condition", "codes": [ED_VISIT],
                          "direct_transition": "End_Heat_ED_Visit"}
    s["End_Heat_ED_Visit"] = {"type": "EncounterEnd", "direct_transition": "Recovery"}
    s["Recovery"] = {"type": "Delay", "range": {"low": 2, "high": 10, "unit": "days"},
                     "direct_transition": "Resolve"}
    s["Resolve"] = {"type": "ConditionEnd", "referenced_by_attribute": "uae_heat_condition",
                    "direct_transition": "Monthly_Delay"}
    s["Terminal"] = {"type": "Terminal"}
    return {
        "name": "UAE Heat Illness",
        "remarks": [
            "Sentinel Grid: seasonal heat-related emergency presentations among adults",
            "(dehydration, hyponatremia, electrolyte disorder, rhabdomyolysis). Stock Synthea",
            "has no heat illness. Heat exhaustion / heat stroke are not coded because their",
            "SNOMED ids could not be verified at build time.",
            "Generated by configs/synthea/build_uae_modules.py — edit that, not this file.",
            "Synthetic data generated by Synthea — not real patient records."],
        "gmf_version": 1,
        "states": s,
    }


def build() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for fname, mod in [("uae_metabolic_risk.json", metabolic_module()),
                       ("uae_heat_illness.json", heat_module())]:
        (OUT / fname).write_text(json.dumps(mod, indent=2) + "\n")
        print(f"wrote {fname}: {len(mod['states'])} states")


if __name__ == "__main__":
    build()
