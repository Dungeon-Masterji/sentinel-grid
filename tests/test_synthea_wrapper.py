def test_demographics_targets():
    df = pd.read_csv(sw.UAE_DEMOGRAPHICS)
    assert len(df) == 10
    w = df["POPESTIMATE2015"] / df["POPESTIMATE2015"].sum()
    assert (df["UAE_AGE_35-44"] == df[[c for c in df if c.startswith("UAE_AGE_")]].max(axis=1)).all()
