    for cols in ([str(i) for i in range(1, 19)],
                 ["WHITE", "BLACK", "ASIAN", "NATIVE", "OTHER"],
                 ["EMIRATI", "SOUTH_ASIAN", "OTHER_ARAB", "WESTERN", "EAST_ASIAN", "AFRICAN"],
                 ["LESS_THAN_HS", "HS_DEGREE", "SOME_COLLEGE", "BS_DEGREE"]):
        assert df[cols].sum(axis=1).round(6).eq(1.0).all(), cols
