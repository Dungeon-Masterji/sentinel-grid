def test_daily_aggregate_on_fixture(parsed):
    events, _ = parsed
    agg = sw.daily_aggregate(events, date(2025, 10, 1), AS_OF)
    assert list(agg.columns) == ["date", "respiratory_encounter_count",
                                 "heat_related_encounter_count", "cardiometabolic_event_count",
                                 "any_encounter_count"]
    assert len(agg) == (AS_OF - date(2025, 10, 1)).days + 1
    assert (agg["respiratory_encounter_count"] <= agg["any_encounter_count"]).all()
    assert (agg["heat_related_encounter_count"] <= agg["any_encounter_count"]).all()
    # The fixture was chosen to contain each signal at least once.
    assert agg["respiratory_encounter_count"].sum() > 0
    assert agg["cardiometabolic_event_count"].sum() > 0
    assert agg["any_encounter_count"].sum() == (
        (events["event_type"] == "encounter")
        & (events["event_time"] >= pd.Timestamp("2025-10-01", tz="UTC"))
        & (events["event_time"] < pd.Timestamp("2026-11-13", tz="UTC"))).sum()


