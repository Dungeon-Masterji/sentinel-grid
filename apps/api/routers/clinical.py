"""Clinical signal pillar — synthetic UAE population (Synthea).

Synthetic data generated by Synthea — not real patient records.

Reads data/processed/clinical/{events,patients}.parquet produced by
packages/pipelines/synth/run_all.py. The aggregation logic lives in
packages/pipelines/synth/synthea_wrapper.py and is loaded with importlib from
whichever location exists:

  * Azure (wwwroot = apps/api contents): ./_vendor/synthea_wrapper.py, copied in
    by .github/workflows/main_sentinel-grid-api.yml
  * Local (repo checkout):               ../../packages/pipelines/synth/synthea_wrapper.py

Parquet files are looked up the same way: $CLINICAL_DATA_DIR, ./data/clinical
(Azure), then <repo>/data/processed/clinical (local).
"""
from __future__ import annotations

import importlib.util
import os
import sys
import threading
from datetime import date, timedelta
from pathlib import Path
from types import ModuleType

from fastapi import APIRouter, HTTPException, Query

router = APIRouter()

API_DIR = Path(__file__).resolve().parents[1]          # apps/api  or  /home/site/wwwroot
REPO_ROOT = API_DIR.parents[1] if API_DIR.name == "api" else None

NOTICE = "Synthetic data generated by Synthea — not real patient records."
MAX_RANGE_DAYS = 366

# UAE age buckets (match configs/synthea/build_uae_geography.py)
AGE_BUCKETS = [(0, 4), (5, 14), (15, 24), (25, 34), (35, 44), (45, 54), (55, 64), (65, 74),
               (75, 200)]


def _candidates(*parts: Path | None) -> list[Path]:
    return [p for p in parts if p is not None]


def _load_wrapper() -> ModuleType:
    env = os.environ.get("SENTINEL_SYNTHEA_WRAPPER")
    paths = _candidates(
        Path(env) if env else None,
        API_DIR / "_vendor" / "synthea_wrapper.py",
        REPO_ROOT / "packages" / "pipelines" / "synth" / "synthea_wrapper.py" if REPO_ROOT else None,
    )
    for p in paths:
        if p.is_file():
            spec = importlib.util.spec_from_file_location("sentinel_synthea_wrapper", p)
            mod = importlib.util.module_from_spec(spec)
            sys.modules[spec.name] = mod      # needed for dataclass/pickle-friendly imports
            spec.loader.exec_module(mod)
            return mod
    raise RuntimeError("synthea_wrapper.py not found; looked in: " + ", ".join(map(str, paths)))


def _data_dir() -> Path | None:
    env = os.environ.get("CLINICAL_DATA_DIR")
    for p in _candidates(Path(env) if env else None,
                         API_DIR / "data" / "clinical",
                         REPO_ROOT / "data" / "processed" / "clinical" if REPO_ROOT else None):
        if (p / "events.parquet").is_file() and (p / "patients.parquet").is_file():
            return p
    return None


class _Store:
    """Lazy, mtime-aware cache of the two parquet files."""

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._key: tuple | None = None
        self.events = None
        self.patients = None
        self.meta: dict = {}
        self._wrapper: ModuleType | None = None

    @property
    def wrapper(self) -> ModuleType:
        if self._wrapper is None:
            self._wrapper = _load_wrapper()
        return self._wrapper

    def load(self):
        d = _data_dir()
        if d is None:
            raise HTTPException(503, detail={"error": "clinical data not available yet",
                                             "hint": "run packages/pipelines/synth/run_all.py"})
        ev_p, pt_p = d / "events.parquet", d / "patients.parquet"
        key = (str(d), ev_p.stat().st_mtime, pt_p.stat().st_mtime)
        with self._lock:
            if key != self._key:
                import pandas as pd
                import pyarrow.parquet as pq
                self.events = pd.read_parquet(ev_p)
                self.patients = pd.read_parquet(pt_p)
                md = pq.read_schema(ev_p).metadata or {}
                self.meta = {k.decode(): v.decode() for k, v in md.items()
                             if k in (b"generated_at", b"synthetic_notice")}
                self._key = key
        return self.events, self.patients


store = _Store()


def _envelope(**payload) -> dict:
    return {"synthetic": True, "notice": NOTICE,
            "generated_at": store.meta.get("generated_at"), **payload}


def _latest_day(events) -> date:
    enc = events.loc[events["event_type"] == "encounter", "event_time"]
    return enc.max().tz_convert("UTC").date()


@router.get("/aggregate")
def aggregate(since: date | None = Query(None, description="YYYY-MM-DD (UTC), inclusive"),
              until: date | None = Query(None, description="YYYY-MM-DD (UTC), inclusive")):
    """Daily respiratory / heat-related / cardiometabolic / all-encounter counts."""
    events, _ = store.load()
    until = until or _latest_day(events)
    since = since or until - timedelta(days=6)
    if since > until:
        raise HTTPException(422, detail="since must be on or before until")
    if (until - since).days >= MAX_RANGE_DAYS:
        raise HTTPException(422, detail=f"range limited to {MAX_RANGE_DAYS} days")
    df = store.wrapper.daily_aggregate(events, since, until)
    days = [{**r, "date": r["date"].isoformat()} for r in df.to_dict(orient="records")]
    totals = {c: int(df[c].sum()) for c in df.columns if c != "date"}
    return _envelope(since=since.isoformat(), until=until.isoformat(),
                     latest_data_day=_latest_day(events).isoformat(), days=days, totals=totals)


@router.get("/patients/summary")
def patients_summary():
    """Demographic breakdown of the living synthetic population."""
    _, patients = store.load()
    alive = patients[~patients["deceased"]]

    def counts(series) -> dict[str, int]:
        return {str(k): int(v) for k, v in series.value_counts().sort_index().items()}

    ages = {}
    for lo, hi in AGE_BUCKETS:
        label = f"{lo}+" if hi >= 200 else f"{lo}-{hi}"
        ages[label] = int(alive["age"].between(lo, hi).sum())
    city = alive["city"].value_counts()
    return _envelope(
        total_patients=int(len(alive)),
        deceased_patients=int(patients["deceased"].sum()),
        age=ages,
        gender=counts(alive["gender"]),
        ethnicity=counts(alive["ethnicity"]),
        city={str(k): int(v) for k, v in city.items()},
    )


@router.get("/conditions/top")
def top_conditions(n: int = Query(20, ge=1, le=200),
                   include_findings: bool = Query(
                       False, description="include SNOMED '(finding)'/'(situation)' concepts "
                                          "such as employment status or medication review")):
    """Most common active SNOMED conditions among living patients (distinct patients)."""
    events, patients = store.load()
    alive_ids = set(patients.loc[~patients["deceased"], "patient_id"])
    cond = events[(events["event_type"] == "condition") & events["event_end"].isna()
                  & events["patient_id"].isin(alive_ids)]
    if not include_findings:
        # Keep disorders, plus the metabolic findings this pillar tracks explicitly.
        keep_findings = {"162864005", "714628002"}   # obesity (BMI 30+), prediabetes
        is_disorder = cond["display"].fillna("").str.endswith("(disorder)")
        cond = cond[is_disorder | cond["code"].isin(keep_findings)]
    g = (cond.groupby("code", observed=True)
             .agg(display=("display", "first"), patients=("patient_id", "nunique"))
             .sort_values(["patients", "code"], ascending=[False, True]).head(n))
    denom = max(len(alive_ids), 1)
    items = [{"code": str(code), "system": "http://snomed.info/sct", "display": r.display,
              "patients": int(r.patients), "prevalence": round(r.patients / denom, 4)}
             for code, r in g.iterrows()]
    return _envelope(n=n, population=denom, conditions=items)
